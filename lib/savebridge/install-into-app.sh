# install-into-app.sh <game.app> <steam appid> [wine-prefix] [存档目录]
# 安装同步启动壳；云同步默认关闭，按游戏持久选择后才 pull / push。
# Unity 的 Wine 存档目录会改名保留，再链接到原生目录，方便恢复不同的进度。
set -eu
APP="$1"; APPID="$2"; PREFIX="${3:-}"
# 第 5 个参数是存档文件的匹配模式（分号隔开）。存档和游戏本体混在一个目录时必须给，
# 不然会把整个游戏传上云。下面按引擎给了默认值。
PATTERN="${5:-}"
HERE="$(cd -- "$(dirname -- "$0")" && pwd)"
C="$APP/Contents"; M="$C/MacOS"
[ -d "$M" ] || { echo "不是一个 .app: $APP" >&2; exit 1; }
[ -x "$HERE/savebridge" ] || { echo "先编译 savebridge" >&2; exit 1; }
[ -f "$HERE/settings.py" ] && [ -f "$HERE/../bundle_safety.py" ] || { echo "缺云同步设置工具" >&2; exit 1; }
SETTINGS_ROOT="${SN_GAMES:-$HOME/Games}"
python3 "$HERE/settings.py" init "$APPID" --root "$SETTINGS_ROOT"

# 存档目录按引擎定。第四个参数可以直接指定，省得猜。
SAVEDIR="${4:-}"
INFO="$C/Resources/Data/app.info"
# 显式给了存档目录、又没给模式时，如果那个目录里有游戏本体，就套一份保守的存档模式
if [ -n "$SAVEDIR" ] && [ -z "$PATTERN" ] && ls "$SAVEDIR"/*.exe >/dev/null 2>&1; then
  PATTERN="*.rvdata2;*.rvdata;*.rxdata;*.save;*.sav;*.dat;persistent"
fi
IS_UNITY=0; [ -f "$INFO" ] && IS_UNITY=1
if [ -n "$SAVEDIR" ]; then
  COMPANY=""; PRODUCT=""
elif [ -f "$INFO" ]; then                      # Unity：Application.persistentDataPath
  COMPANY=$(sed -n 1p "$INFO"); PRODUCT=$(sed -n 2p "$INFO")
  SAVEDIR="$HOME/Library/Application Support/$COMPANY/$PRODUCT"
elif [ -d "$C/Resources/app.nw" ]; then        # NW.js：nw 的 userDataDir，按 package.json 的 name
  _n=$(python3 -c "import json,sys;print(json.load(open(sys.argv[1])).get('name','game'))" "$C/Resources/app.nw/package.json" 2>/dev/null || echo game)
  SAVEDIR="$HOME/Library/Application Support/$_n"
elif ls "$C/Resources"/*.pck >/dev/null 2>&1; then   # Godot：user:// 落在这里
  _n=$(basename "$(ls "$C/Resources"/*.pck | head -1)" .pck)
  SAVEDIR="$HOME/Library/Application Support/Godot/app_userdata/$_n"
elif ls "$C/Resources"/*.xp3 >/dev/null 2>&1; then   # 吉里吉里：krkrsdl2 按游戏名分目录
  SAVEDIR="$HOME/Library/Application Support/krkrsdl2/$(basename "$APP" .app)"
elif [ -d "$C/Resources/game" ]; then          # mkxp-z / Ren'Py：存档在游戏目录里
  SAVEDIR="$C/Resources/game"
  [ -n "$PATTERN" ] || PATTERN="*.rvdata2;*.rvdata;*.rxdata;*.save;*.sav;persistent"
else
  echo "认不出这个包的存档目录，请用第四个参数显式指定" >&2; exit 1
fi
cp "$HERE/savebridge" "$M/savebridge"
cp "$HERE/libsteam_api.dylib" "$M/libsteam_api.dylib" 2>/dev/null || true
EXE=$(/usr/libexec/PlistBuddy -c "Print CFBundleExecutable" "$C/Info.plist")
GAME=$(ls "$M" | grep -vxE "launcher|savebridge|libsteam_api.dylib|steam_appid.txt|savebridge-settings.py|bundle_safety.py|__pycache__" | head -1)
BID=$(/usr/libexec/PlistBuddy -c "Print CFBundleIdentifier" "$C/Info.plist")
echo "$APPID" > "$M/steam_appid.txt"
mkdir -p "$SAVEDIR"
cp "$HERE/settings.py" "$M/savebridge-settings.py"
cp "$HERE/../bundle_safety.py" "$M/bundle_safety.py"
quote(){ python3 -c 'import shlex,sys; print(shlex.quote(sys.argv[1]))' "$1"; }
SAVE_Q=$(quote "$SAVEDIR"); ROOT_Q=$(quote "$SETTINGS_ROOT")
GAME_Q=$(quote "$GAME"); PATTERN_Q=$(quote "$PATTERN")

cat > "$M/launcher" <<LAUNCH
#!/bin/bash
# generated by assemble-mac-app.sh + savebridge/install-into-app.sh
D="\$(cd -- "\$(dirname -- "\$0")" && pwd)"
cd "\$D" || exit 1
SAVEDIR=$SAVE_Q
CHOICE_ROOT=$ROOT_Q
GAME=$GAME_Q
PATTERN=$PATTERN_Q
if [ -f "\$D/steam_appid.txt" ]; then
  _id=\$(tr -d ' \t\r\n' < "\$D/steam_appid.txt")
  [ -n "\$_id" ] && export SteamAppId="\$_id" SteamGameId="\$_id"
fi
# 单次环境变量不能授予启用选择；0 仍可用作测试和紧急停用开关。
SYNC=0
if [ "\${SN_SAVEBRIDGE:-}" != 0 ] && python3 -B "\$D/savebridge-settings.py" check "\$_id" --root "\$CHOICE_ROOT"; then SYNC=1; fi
sync_error(){
  local status="\$1" phase="\$2" message
  if [ "\$status" = 3 ]; then
    message="Cloud save sync conflict (\$phase): both versions retained. Check the save folder and .savebridge.log; sync stopped."
  else
    message="Cloud save sync failed (\$phase, exit \$status). Check .savebridge.log; sync stopped."
  fi
  printf '%s\\n' "\$message" >&2
  osascript - "\$message" <<'NOTICE'
on run argv
  display alert "Cloud save sync" message (item 1 of argv) as warning
end run
NOTICE
}
if [ "\$SYNC" = 1 ]; then
  "\$D/savebridge" "\$_id" pull "\$SAVEDIR" "\$PATTERN" >> "\$SAVEDIR/.savebridge.log" 2>&1
  _sync_rc=\$?
  if [ "\$_sync_rc" != 0 ]; then sync_error "\$_sync_rc" pull; exit "\$_sync_rc"; fi
fi
# First launch (no saved display settings yet): windowed, so the desktop and cursor stay reachable.
# Only Unity understands these flags; other engines get none.
_extra=""
if [ "$IS_UNITY" = 1 ] && [ ! -f "\$HOME/Library/Preferences/$BID.plist" ]; then _extra="-screen-fullscreen 0 -screen-width 1280 -screen-height 720"; fi
"\$D/\$GAME" \$_extra "\$@"
_rc=\$?
# Push whatever you just played back up, so the next device sees it.
if [ "\$SYNC" = 1 ]; then
  "\$D/savebridge" "\$_id" push "\$SAVEDIR" "\$PATTERN" >> "\$SAVEDIR/.savebridge.log" 2>&1
  _sync_rc=\$?
  if [ "\$_sync_rc" != 0 ]; then sync_error "\$_sync_rc" push; exit "\$_sync_rc"; fi
fi
exit \$_rc
LAUNCH
chmod +x "$M/launcher"
/usr/libexec/PlistBuddy -c "Set :CFBundleExecutable launcher" "$C/Info.plist" 2>/dev/null || true

if [ -n "$PREFIX" ]; then
  WIN="$PREFIX/drive_c/users"
  for U in "$WIN"/*/; do
    [ -n "$COMPANY" ] || continue      # 只有 Unity 知道 prefix 里存档在哪
    LL="$U/AppData/LocalLow/$COMPANY/$PRODUCT"
    [ -e "$LL" ] || continue
    if [ ! -L "$LL" ]; then
      # 同名的不同存档不会被合并；原目录改名保留，不能在合并后删除。
      /usr/bin/rsync -a --ignore-existing "$LL"/ "$SAVEDIR"/
      KEEP="$(mktemp -d "$LL.savebridge-backup.XXXXXX")"
      mv "$LL" "$KEEP/original"
      ln -s "$SAVEDIR" "$LL"
      echo "Wine 原存档保留在：$KEEP/original"
      echo "Wine 存档目录已指向原生存档：$LL"
    fi
  done
fi
codesign --force --sign - "$APP" 2>&1 | grep -v "replacing existing" || true
echo "装好了：$APP"
echo "  存档目录 $SAVEDIR"
echo "  云同步默认关闭：dryport cloud enable ${APPID} 持久启用；cloud disable ${APPID} 关闭。"
[ -n "$PATTERN" ] && echo "  只同步   $PATTERN"
exit 0
