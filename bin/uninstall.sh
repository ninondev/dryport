# ─────────────────────────────────────────────────────────────
#  uninstall.sh — 撤销这套工具在本机留下的东西
#
#    ./uninstall.sh          预演: 只列出会删什么, 一个字节都不动(默认)
#    ./uninstall.sh --go     逐类问你一次, 你答 y 才删那一类
#
#  只碰自己建的东西。steamcmd 下载的游戏文件、Steam 本体、你的存档、
#  编好的运行时一律不删，最后一节会把这些列出来让你确认。
# ─────────────────────────────────────────────────────────────
set -uo pipefail

GAMES="$HOME/Games"
RT="$GAMES/runtimes"
STEAM="$HOME/Library/Application Support/Steam"
MIRROR="$RT/steam-shortcut-mirror.py"
MARKS="$HOME/Library/Application Support/dryport"

GO=0
for a in "$@"; do
  case "$a" in
    --go|--yes) GO=1;;
    --dry-run)  GO=0;;
    -h|--help)  sed -n '2,12p' "$0"; exit 0;;
    *) echo "不认识的参数: $a (只有 --go / --dry-run)" >&2; exit 2;;
  esac
done

hd(){ printf "\n\033[1m%s\033[0m\n" "$*"; }
item(){ printf "    %s\n" "$*"; }

# 逐类确认。预演模式下一律返回「不删」。
ask(){
  local what="$1"
  [ "$GO" = 1 ] || { echo "    → 预演, 不删。要真删: ./uninstall.sh --go"; return 1; }
  local ans
  printf "    → 删掉这一类吗? [y/N] "
  read -r ans </dev/tty || return 1
  case "$ans" in y|Y|yes|YES) return 0;; *) echo "    跳过 $what"; return 1;; esac
}

# 这个 .app 是不是本工具生成的。认 bundle id 前缀, 外加 mkxp 路线的标记文件。
# 不认名字, 也不按目录位置一刀切，免得误删用户自己放进 ~/Games 的 app。
is_ours(){
  local app="$1" bid
  bid=$(/usr/libexec/PlistBuddy -c "Print :CFBundleIdentifier" "$app/Contents/Info.plist" 2>/dev/null)
  case "$bid" in
    com.unity-retarget.*|io.nwjs.wrap.*|org.godotengine.wrapped.*|krkrsdl2.wrap.*|local.winewrap.*) return 0;;
  esac
  grep -q "generated by dryport" "$app/Contents/Game/mkxp.json" 2>/dev/null && return 0
  return 1
}

echo "═══ dryport 卸载 ═══"
if [ "$GO" = 1 ]; then
  echo "（真删模式。每一类都会单独问你一次。）"
else
  echo "（预演模式，什么都不会改。确认无误后: ./uninstall.sh --go）"
fi

# ── 1. 打包好的 .app ──
hd "【1. 本工具打包的游戏 .app】"
APPS=()
for a in "$GAMES"/*.app; do
  [ -d "$a" ] || continue
  is_ours "$a" && APPS+=("$a")
done
if [ ${#APPS[@]} -eq 0 ]; then
  echo "    没有"
else
  for a in "${APPS[@]}"; do
    item "$(basename "$a")   $(du -sh "$a" 2>/dev/null | cut -f1)   $(/usr/libexec/PlistBuddy -c "Print :CFBundleIdentifier" "$a/Contents/Info.plist" 2>/dev/null)"
  done
  echo "    注意: RGSS(mkxp-z) 路线的存档在 <app>/Contents/Game/Save*.rvdata2, 删 app 会一起没。"
  echo "          Unity / NW.js / Godot / 吉里吉里 路线的存档在 app 外面, 删 app 不影响。"
  if ask ".app"; then
    for a in "${APPS[@]}"; do rm -rf "$a" && echo "    已删 $(basename "$a")"; done
  fi
fi

# ── 2. Steam 库里的快捷方式 ──
hd "【2. Steam 库里我们加的非 Steam 快捷方式】"
SC_APPS=()
SC_IDS=()
if [ -f "$MIRROR" ]; then
  for a in "$GAMES"/*.app; do
    [ -d "$a" ] || continue
    is_ours "$a" || continue
    out=$(python3 "$MIRROR" --find "$a" 2>/dev/null) || continue
    [ -n "$out" ] || continue
    SC_APPS+=("$a")
    while read -r u i n; do
      item "账号 $u  快捷方式 appid=$i  $n"
      SC_IDS+=("$i")
    done <<<"$out"
  done
fi
if [ ${#SC_APPS[@]} -eq 0 ]; then
  echo "    没有（或者 .app 已经先被删掉了，这时按 exe 路径查不到，需要在 Steam 库里手工右键删）"
else
  echo "    删法: 先把 shortcuts.vdf 原样解析再序列化, 和磁盘字节逐字节比对,"
  echo "          对不上就一个字节都不写; 对得上才备份 .bak-<时间戳> 再删那一条, 删完回读核对。"
  echo "    Steam 正在运行的话, 它退出时可能用内存里的旧副本盖回去，建议先退出 Steam。"
  if ask "Steam 快捷方式"; then
    if pgrep -qx steam_osx 2>/dev/null || pgrep -qf "Steam.AppBundle" 2>/dev/null; then
      echo "    [注意] Steam 还在跑, 删了可能被它盖回去。仍然继续。"
    fi
    for a in "${SC_APPS[@]}"; do
      echo "    $(basename "$a"):"
      python3 "$MIRROR" --remove "$a"
    done
    # grid 封面: 按上面拿到的快捷方式 appid 删, 不按名字猜
    for i in ${SC_IDS[@]+"${SC_IDS[@]}"}; do
      for g in "$STEAM"/userdata/*/config/grid/"$i"*; do
        [ -e "$g" ] && rm -f "$g" && echo "    已删封面 $(basename "$g")"
      done
    done
  fi
fi

# ── 3. 中间产物 ──
hd "【3. 打包中间产物】"
MID=()
[ -d "$GAMES/.unity-work" ] && MID+=("$GAMES/.unity-work")
[ -d "$MARKS" ] && MID+=("$MARKS")
if [ ${#MID[@]} -eq 0 ]; then
  echo "    没有"
else
  for m in "${MID[@]}"; do item "$m   $(du -sh "$m" 2>/dev/null | cut -f1)"; done
  echo "    .unity-work 是着色器重定向的输出与日志; dryport 目录只有「这个游戏启动过一次了」的空标记文件"
  echo "    (删了之后下次启动会再窗口化一次, 无害)。"
  ask "中间产物" && for m in "${MID[@]}"; do rm -rf "$m" && echo "    已删 $m"; done
fi

# ── 4. 下载缓存 ──
hd "【4. runtimes 下的下载缓存（不含编好的运行时）】"
CACHE=()
while IFS= read -r f; do [ -n "$f" ] && CACHE+=("$f"); done < <(
  find "$RT/unity-players" -maxdepth 2 -name 'mac-mono-support.pkg' 2>/dev/null
  find "$RT/godot" -maxdepth 2 -name 'macos-template.zip' 2>/dev/null
  find "$RT/nwjs" -maxdepth 2 -name '*.zip' 2>/dev/null
  ls "$RT"/wine-staging.tar.xz 2>/dev/null
)
# 故意不列 cx-sources.tar.gz: 那是另一条在建路线(wine-cx)的源码包, 不是可随时重下的运行时缓存。
if [ ${#CACHE[@]} -eq 0 ]; then
  echo "    没有"
else
  TOTAL=0
  for f in "${CACHE[@]}"; do
    sz=$(stat -f%z "$f" 2>/dev/null || echo 0); TOTAL=$((TOTAL+sz))
    item "$(echo "$f" | sed "s|$HOME|~|")   $(( sz / 1048576 )) MB"
  done
  echo "    共 $(( TOTAL / 1048576 )) MB。这些是安装包/压缩包本身, 已经解开的运行时不动;"
  echo "    删了以后需要时会重新下。"
  ask "下载缓存" && for f in "${CACHE[@]}"; do rm -f "$f" && echo "    已删 $(basename "$f")"; done
fi

# ── 5. 不会碰的 ──
hd "【不会碰的东西（要清得手工来）】"
item "steamcmd 下载的游戏原始文件: $(ls -d "$GAMES"/*/ 2>/dev/null | grep -v '/runtimes/\|/patches/' | wc -l | tr -d ' ') 个目录, 共 $(du -sh "$GAMES" 2>/dev/null | cut -f1) 里的大头"
item "Steam 本体与其它任何游戏"
item "编好的运行时: mkxp-z、krkrsdl2、NW.js、Godot 模板、Unity 播放器、hlslcc、Wine。要清: rm -rf ~/Games/runtimes"
item "工具本体: ~/Games/dryport、各 wrap 脚本、README.md"
item "游戏存档: ~/Library/Application Support/krkrsdl2-*/ 、~/Library/Application Support/Godot/app_userdata/ 、~/Library/Preferences/com.unity-retarget.*.plist"
item "系统设置: 一处都没改过"

echo
if [ "$GO" = 1 ]; then
  echo "完成。动过 Steam 快捷方式的话, Steam 需重启一次才刷新库。"
else
  echo "以上为预演。真删: ./uninstall.sh --go"
fi
